// Run with `npm run build:canonical-json-vectors`. Regenerates
// tests/fixtures/canonical-json-vectors.json from the TypeScript
// encoder, so the expected strings are produced by the implementation rather
// than typed by hand. The Swift client verifies the same file, which is what
// makes it a conformance fixture rather than a snapshot.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const { canonicalJson } = await import("../packages/protocol/src/canonical-json.ts");

const cases = [
  ["keys sort by UTF-16 code unit, not case-insensitively", { b: 1, A: 2, a: 3, B: 4 }],
  ["digit runs sort lexicographically, not numerically", { item10: 1, item9: 2, item1: 3 }],
  ["underscore and hyphen order by code unit", { a_b: 1, "a-b": 2, aQb: 3 }],
  [
    "nested objects sort at every level",
    { outer: { z: 1, a: { y: 2, b: 3 } }, first: [{ d: 1, c: 2 }] }
  ],
  [
    "forward slashes and non-ASCII are not escaped",
    { path: "/api/v1/relay", text: "häirintä — ✅" }
  ],
  [
    "control characters use the short escapes where they exist",
    { s: `a\nb\tc${String.fromCharCode(0)}d${String.fromCharCode(31)}e"f\\g` }
  ],
  [
    "integral numbers carry no fractional part",
    { version: 1, counter: 4294967296, zero: 0, negative: -7 }
  ],
  [
    "ECMAScript number thresholds and shortest round trips",
    {
      negativeZero: -0,
      belowFixedThreshold: 1e-7,
      fixedThreshold: 1e-6,
      largeFixed: 1e20,
      scientificThreshold: 1e21,
      largeRoundedInteger: 1000000000000000100,
      smallest: Number.MIN_VALUE,
      largest: Number.MAX_VALUE
    }
  ],
  ["booleans, null, and empty containers", { t: true, f: false, n: null, arr: [], obj: {} }]
];

const document = {
  comment:
    "Shared conformance vectors, generated by scripts/build-canonical-json-vectors.mjs. " +
    "The TypeScript canonicalJson and the Swift CanonicalJSON.encode must both produce " +
    "`encoded` for `value`. Signature payloads are only interoperable while they agree.",
  vectors: cases.map(([name, value]) => ({ name, value, encoded: canonicalJson(value) }))
};

const target = fileURLToPath(new URL("../tests/fixtures/canonical-json-vectors.json", import.meta.url));
writeFileSync(target, `${JSON.stringify(document, null, 2)}\n`, "utf8");
process.stdout.write(`wrote ${document.vectors.length} vectors to ${target}\n`);
